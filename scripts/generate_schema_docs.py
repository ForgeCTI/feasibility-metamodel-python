"""Generate docs/schema.md from the registry (entities, attributes, relationships, multiplicities).

Run from the repository root:
    python scripts/generate_schema_docs.py --src src --output docs/schema.md
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

DOMAINS = (("organization", "Organization"), ("infrastructure", "Infrastructure"), ("cyberThreat", "Cyber threat"))
KC = {"concept": "a-priori, generic", "system": "a-priori, instance-specific", "posteriori": "a-posteriori"}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--src", default="src")
    parser.add_argument("--output", default="docs/schema.md")
    args = parser.parse_args()
    sys.path.insert(0, str(Path(args.src).resolve()))
    from metamodel.core.Registry import Registry
    from metamodel.core.Schema import describe_entity, describe_relationship

    registry = Registry.load_default()
    lines = [
        "# Schema reference",
        "",
        "Generated by `scripts/generate_schema_docs.py` from the registry; do not edit by hand.",
        "The same information is printed by `metamodel schema` (add `--json` for machine-readable output).",
        "",
        "Multiplicities are written at the source and target ends of each association, as in the paper:",
        "`A [m] --label--> [n] B` means that each `B` is related to `m` instances of `A` and each `A` to `n` instances of `B`.",
        "Associations with the same label and source but several target types (e.g. `protects`) are implemented by one",
        "class per target type; their target multiplicity is validated on the union of the classes.",
        "",
    ]
    for domain, title in DOMAINS:
        lines += [f"## {title}", "", "### Entities", "",
                  "| Entity | Superclass | Knowledge | Attributes | Description |", "|---|---|---|---|---|"]
        for cls in registry.get_entity_classes():
            d = describe_entity(cls)
            if d["domain"] != domain:
                continue
            attrs = ", ".join(f"`{k}`: {v}" for k, v in d["attributes"].items()) or "—"
            doc = (cls.__doc__ or "").strip().splitlines()[0] if cls.__doc__ else ""
            lines.append(f"| `{d['name']}` | {('`' + d['superclass'] + '`') if d['superclass'] else '—'} | "
                         f"{KC.get(d['knowledge_class'], '—')} | {attrs} | {doc} |")
        lines += ["", "### Relationships", "",
                  "| Label | Source [mult.] → [mult.] Target | Class | Attributes |", "|---|---|---|---|"]
        for cls in registry.get_relationship_classes():
            if cls.__module__.split(".")[1] != domain:
                continue
            r = describe_relationship(cls)
            attrs = ", ".join(f"`{k}`: {v}" for k, v in r["attributes"].items()) or "—"
            lines.append(f"| `{r['label']}` | `{r['source']}` [{r['source_cardinality']}] → "
                         f"[{r['target_cardinality']}] `{r['target']}` | `{r['name']}` | {attrs} |")
        lines.append("")
    Path(args.output).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
